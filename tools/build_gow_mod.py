"""Build the in-game half of GoW: the mod files the game loads after WarFighter.

This repository folder IS the mod (load order: vanilla, WarFighter, GoW). The game only reads mod.info
and resource/; everything else here is development material.

  mod.info                                               written if missing
  resource/script/multiplayer/modes/conquest.lua         GENERATED: the installed WarFighter conquest.lua,
                                                         unchanged, plus one line that loads the GoW bridge
  resource/script/multiplayer/modes/conquest/gow_bridge.lua   hand-written (tracked)

Re-run after every WarFighter update so the generated file follows WF's own.

    python tools/build_gow_mod.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WF = Path(json.loads((ROOT / "tools" / "paths.json").read_text(encoding="utf-8"))["WF"])
REL = Path("resource") / "script" / "multiplayer" / "modes" / "conquest.lua"
HOOK = "require([[/script/multiplayer/modes/conquest/gow_bridge]]) -- GoW campaign bridge"

MOD_INFO = """{mod
	{name "Gates of Warfighter"}
	{tags "singleplayer"}
	{desc "GoW: strategic campaign layer for WarFighter GoH. Requires WarFighter GoH, loaded before this mod. Based on Gates of Europa, with its author's permission."}
	{minGameVersion "any"}
	{maxGameVersion "any"}
}
"""


def main() -> None:
    src = (WF / REL).read_bytes()
    text = src.decode("utf-8")
    if "gow_bridge" in text:
        raise SystemExit("WarFighter's conquest.lua already mentions gow_bridge; refusing to double-hook")
    digest = hashlib.sha256(src).hexdigest().upper()
    header = (f"-- GENERATED by tools/build_gow_mod.py. Do not edit.\n"
              f"-- Source: WarFighter GoH resource/script/multiplayer/modes/conquest.lua (SHA256 {digest[:16]}...)\n"
              f"-- Only difference from WarFighter's file: the last line, which loads the GoW bridge.\n")
    out = ROOT / REL
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + text.rstrip("\r\n") + "\n\n" + HOOK + "\n", encoding="utf-8", newline="\n")
    info = ROOT / "mod.info"
    if not info.exists():
        info.write_text(MOD_INFO, encoding="utf-8", newline="\n")
    print(f"wrote {REL} from WarFighter conquest.lua {digest[:16]}; mod.info {'present' if info.exists() else 'missing'}")
    print(f"mod id for options.set / save status: mod_{ROOT.name}:0")


if __name__ == "__main__":
    main()
